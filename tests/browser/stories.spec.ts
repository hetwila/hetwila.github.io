test('the bookshelf, inline concepts, chapter anchors and story full-text search work on mobile', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error' || /hydration/i.test(message.text())) errors.push(message.text()) })
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  await page.getByRole('button', { name: '打开菜单', exact: true }).click()
  await page.getByRole('dialog').getByRole('link', { name: '故事书架', exact: true }).click()
  await page.getByRole('link', { name: '第一次选择', exact: true }).click()
  await expect(page.getByRole('button', { name: '故事目录', exact: true })).toHaveCount(1)
  await page.locator('.mobile-toc').getByRole('button', { name: '故事目录', exact: true }).click()
  await page.locator('.mobile-toc').getByRole('link', { name: '六', exact: true }).click()
  await expect.poll(() => decodeURI(page.url())).toContain('#六')
  await expect(page.locator('.story-prose #六')).toBeInViewport()
  await page.locator('.story-prose').getByRole('link', { name: '诺菲莉亚', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('诺菲莉亚·薇尔希·伊拉奈德')
  await page.getByRole('region', { name: '相关故事' }).getByRole('link', { name: '第一次选择', exact: true }).click()
  await page.getByRole('button', { name: '搜索设定', exact: true }).click()
  await page.getByRole('textbox', { name: '搜索关键词' }).fill('甜点烤好的香气')
  await expect(page.locator('.search-result').filter({ hasText: '第一次选择' })).toBeVisible()
  await page.getByRole('textbox', { name: '搜索关键词' }).fill('H48-08')
  await expect(page.locator('.search-result').first().locator('strong')).toHaveText('1747年议长选举')
  expect(errors).toEqual([])
})

test('HTTP exports distinguish story-local prose, exact originals and objective setting relations', async ({ request }) => {
  const manifest = await (await request.get('/data/v1/manifest.json')).json()
  expect(manifest.storyCount).toBe(1)
  expect(manifest.wikiCount).toBe(18)
  const catalog = await (await request.get(manifest.catalog)).json()
  const entry = catalog.find((item: { entityType: string }) => item.entityType === 'story')
  const story = await (await request.get(entry.jsonUrl)).json()
  expect(story).toMatchObject({ uid: 'story:第一次选择', scopeUid: 'story:第一次选择', narrativeLayer: 'fiction', factStatus: 'story-local', worldTime: { year: 1747 } })
  const original = await (await request.get(story.originalMarkdownUrl)).body()
  expect(original.equals(await readFile(new URL('../../sources/stories/第一次选择.md', import.meta.url)))).toBeTruthy()
  expect(createHash('sha256').update(original).digest('hex')).toBe(story.originalSha256)
  expect(manifest.files[story.originalMarkdownUrl]).toBe(story.originalSha256)
  expect(story.relations).toContainEqual(expect.objectContaining({ type: 'depicts', target: 'event:h48-08', targetPath: '/wiki/1747年议长选举' }))
  const eventEntry = catalog.find((item: { uid: string }) => item.uid === 'event:h48-08')
  const event = await (await request.get(eventEntry.jsonUrl)).json()
  expect(event.factStatus).toBe('canon')
  expect(event.backlinks).toContainEqual(expect.objectContaining({ type: 'depicts', source: story.uid, sourcePath: story.path }))
  expect((await request.get('/stories/不存在的作品')).status()).toBe(404)
})
