test('stories and ID-only pages share comments; encyclopedia and forum pages have no comments', async ({ page }) => {
  await commentFixture(page)
  await page.goto('/stories/第一次选择')
  const section = page.locator('.comment-section')
  await expect(section.getByText('其他读者', { exact: true })).toBeVisible()
  await expect(section.getByRole('link', { name: '登录参与讨论' })).toHaveAttribute('href', /returnTo=.*comments/)
  await expect(section.getByRole('button', { name: '发表评论', exact: true })).toHaveCount(0)
  await page.goto(`/comments?id=${sectionId}`)
  await expect(page.getByRole('heading', { name: '独立评论区', exact: true })).toBeVisible()
  await expect(page.locator('.comment-section').getByText('其他读者', { exact: true })).toBeVisible()
  await page.goto(`/comments?id=${standaloneId}`)
  await expect(page.getByText('还没有评论。', { exact: true })).toBeVisible()
  for (const path of ['/wiki/禁制', '/forum/threads/皇族历史同人讨论/page/1']) {
    await page.goto(path); await expect(page.locator('.comment-section')).toHaveCount(0)
  }
  await page.goto('/comments?id=invalid'); await expect(page.getByText('请通过有效的评论区链接访问。')).toBeVisible()
})

test('guest previews, posts, edits and deletes only their own comments with both timestamps', async ({ page }) => {
  const api = await commentFixture(page, 'guest')
  await page.goto('/stories/第一次选择')
  const section = page.locator('.comment-section')
  await section.getByLabel('写评论', { exact: true }).fill('# 新评论标题\n\n**谢谢分享**')
  await section.getByRole('button', { name: '预览评论', exact: true }).click()
  await expect(section.getByRole('region', { name: '评论预览' }).locator('strong')).toHaveText('谢谢分享')
  await section.getByRole('button', { name: '发表评论', exact: true }).click()
  await expect(section.locator('.comment-item').filter({ hasText: '新评论标题' })).toBeVisible()
  expect(api.requests.find(r => r.path === 'article_comments' && r.method === 'POST')?.body).toEqual({ section_id: sectionId, body: '# 新评论标题\n\n**谢谢分享**' })
  const own = section.locator('.comment-item').filter({ hasText: '新评论标题' })
  await expect(own.locator('time')).toHaveCount(2)
  const published = await own.locator('time').first().getAttribute('datetime')
  await own.getByRole('button', { name: '编辑评论', exact: true }).click()
  await section.getByLabel('编辑评论', { exact: true }).fill('修改后的评论内容')
  await section.getByRole('button', { name: '保存修改', exact: true }).click()
  const edited = section.locator('.comment-item').filter({ hasText: '修改后的评论内容' })
  await expect(edited.locator('time').first()).toHaveAttribute('datetime', published!)
  await expect(edited.locator('time').last()).not.toHaveAttribute('datetime', published!)
  const other = section.locator('.comment-item').filter({ hasText: '另一位读者的评论' })
  await expect(other.getByRole('button')).toHaveCount(0)
  await edited.getByRole('button', { name: '删除评论', exact: true }).click()
  await page.getByRole('button', { name: '确认删除评论', exact: true }).click()
  await expect(section.getByText('修改后的评论内容', { exact: true })).toHaveCount(0)
})

test('admin manages both switches, deletes any comment and creates an unlinked section', async ({ page }) => {
  const api = await commentFixture(page, 'admin')
  await page.goto(`/comments?id=${sectionId}`)
  const area = page.locator('.comment-section')
  await area.getByRole('switch', { name: '允许评论区投稿', exact: true }).click()
  await expect(area.getByText('评论区已暂停接收新评论。')).toBeVisible()
  await expect(area.getByRole('button', { name: '发表评论', exact: true })).toHaveCount(0)
  await expect(area.getByRole('button', { name: '编辑评论', exact: true })).toHaveCount(1)
  await area.getByRole('switch', { name: '允许评论区投稿', exact: true }).click()
  await area.getByRole('switch', { name: '允许这篇文章被评论', exact: true }).click()
  await expect(area.getByText('这篇文章已关闭新评论。')).toBeVisible()
  const other = area.locator('.comment-item').filter({ hasText: '另一位读者的评论' })
  await expect(other.getByRole('button', { name: '编辑评论', exact: true })).toHaveCount(0)
  await other.getByRole('button', { name: '删除评论', exact: true }).click()
  await page.getByRole('button', { name: '确认删除评论', exact: true }).click()
  await expect(other).toHaveCount(0)
  await page.goto('/account/admin')
  await page.getByRole('tab', { name: '评论区', exact: true }).click()
  await page.getByRole('button', { name: '创建独立评论区', exact: true }).click()
  await page.getByLabel('评论区名称', { exact: true }).fill('不依赖文章的讨论')
  await page.getByRole('button', { name: '创建评论区', exact: true }).click()
  await expect(page.getByRole('heading', { name: '不依赖文章的讨论' })).toBeVisible()
  const created = api.sections.find(s => s.title === '不依赖文章的讨论')!
  expect(created.article).toBeNull()
  await page.goto(`/comments?id=${created.id}`)
  await page.getByLabel('写评论', { exact: true }).fill('独立评论区正常投稿')
  await page.getByRole('button', { name: '发表评论', exact: true }).click()
  await expect(page.locator('.comment-item').getByText('独立评论区正常投稿')).toBeVisible()
})

test('pagination, read recovery and failed writes retain usable state and drafts', async ({ page }) => {
  const api = await commentFixture(page, 'guest', 22)
  await page.goto(`/comments?id=${sectionId}`)
  await expect(page.locator('.comment-item')).toHaveCount(20)
  await page.getByRole('button', { name: /下一页/ }).click()
  await expect(page.locator('.comment-item')).toHaveCount(2)
  await expect(page.getByText('另一位读者的评论 21', { exact: true })).toBeVisible()
  api.sections[0]!.posting_enabled = false
  await page.getByLabel('写评论', { exact: true }).fill('保留这段尚未成功发表的内容')
  await page.getByRole('button', { name: '发表评论', exact: true }).click()
  await expect(page.getByText(/发表失败，请检查登录状态/)).toBeVisible()
  await expect(page.getByLabel('写评论', { exact: true })).toHaveValue('保留这段尚未成功发表的内容')
  api.sections[0]!.posting_enabled = true
  api.state.failReads = true
  await page.getByRole('button', { name: '刷新评论', exact: true }).click()
  await expect(page.getByText('评论暂时无法读取，请稍后重试。')).toBeVisible()
  api.state.failReads = false
  await page.getByRole('button', { name: '刷新评论', exact: true }).click()
  await expect(page.getByText('评论暂时无法读取，请稍后重试。')).toHaveCount(0)
  await expect(page.getByLabel('写评论', { exact: true })).toHaveValue('保留这段尚未成功发表的内容')
})

